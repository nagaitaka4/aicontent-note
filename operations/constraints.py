def lines(scope="write"):
    """制約を「カテゴリ: 本文」の行リストで返す。scope='all'で全件。"""
    out, last = [], None
    for sc, cat, text in CONSTRAINTS:
        if scope != "all" and sc != scope:
            continue
        if cat != last:
            out.append(f"\n**{cat}**")
            last = cat
        out.append(f"- {text}")
    return out


